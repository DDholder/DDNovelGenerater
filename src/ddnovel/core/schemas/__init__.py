def export_json_schemas() -> dict[str, dict[str, Any]]:
    """导出全部公开模型的 JSON Schema，供 T13 MCP 参数声明与 T14 SKILL.md 字段说明引用。"""
    return {
        model_cls.__name__: TypeAdapter(model_cls).json_schema(mode="serialization")
        for model_cls in _EXPORTED_MODELS
    }


